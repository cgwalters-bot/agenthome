/// The first non-blank line under the title, or the first line without one.
fn first_line(text: &str) -> Option<&str> {
    let mut lines = text.lines().filter(|line| !line.trim().is_empty());
    let first = lines.next()?;
    if first.starts_with("# ") {
        lines.next()
    } else {
        Some(first)
    }
}

