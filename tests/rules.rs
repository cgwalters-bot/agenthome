#[test]
fn this_repositorys_documents_start_with_the_notice() {
    let exempt = Regex::new(NOTICE_EXEMPT).unwrap();
    let docs: Vec<_> = walk(root())
        .into_iter()
        .filter(|path| path.ends_with(".md") && !exempt.is_match(path))
        .collect();
    assert!(
        docs.iter().any(|path| path == "README.md"),
        "README.md was read"
    );
    for path in docs {
        assert_eq!(
            first_line(&read(&path)),
            Some(NOTICE),
            "{path} starts with the notice"
        );
    }
    assert_eq!(
        first_line(&format!("# T\n\n{NOTICE}\n\nBody.\n")),
        Some(NOTICE)
    );
    assert_eq!(first_line(&format!("{NOTICE}\n")), Some(NOTICE));
    assert_ne!(
        first_line(&format!("# T\n\nBody.\n\n{NOTICE}\n")),
        Some(NOTICE)
    );
}

// The JavaScript was ported to this crate; keep it from coming back.
#[test]
fn no_javascript_files() {
    let javascript: Vec<_> = walk(root())
        .into_iter()
        .filter(|path| {
            Path::new(path)
                .extension()
                .and_then(|e| e.to_str())
                .is_some_and(|e| ["js", "mjs", "cjs"].contains(&e.to_ascii_lowercase().as_str()))
        })
        .collect();
    assert!(
        javascript.is_empty(),
        "port these to Rust instead: {javascript:?}"
    );
}

/// Markdown paragraphs, split on blank lines.
fn paragraphs(text: &str) -> Vec<&str> {
    Regex::new(r"\n\s*\n").unwrap().split(text).collect()
}

#[test]
fn the_generated_document_notice_is_its_own_paragraph() {
    let agents = read("opencode/AGENTS.md");
    let notice = paragraphs(&agents)
        .into_iter()
        .find(|p| p.contains(NOTICE))
        .expect("opencode/AGENTS.md carries the notice");
    assert!(
        !notice.contains(ATTRIBUTION),
        "the notice is not part of the trailer paragraph"
    );
}

/// The paragraph after a "Code navigation" heading, joined into one line.
fn navigation(text: &str) -> String {
    let parts = paragraphs(text);
    let heading = Regex::new(r"^#+ Code navigation$").unwrap();
    let i = parts
        .iter()
        .position(|p| heading.is_match(p.trim()))
        .expect("has a Code navigation section");
    parts[i + 1]
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
}

// Hosted runs do not install the structural tools (agenthome#29), so every
// copy of the navigation rule makes them conditional on being on PATH and
// names the fallback, or a run spends its turns on `command not found`.
// The root AGENTS.md's paragraph is copied into the standing rules.
#[test]
fn structural_code_navigation_is_conditional_on_the_tools_being_installed() {
    let standing = navigation(&read("opencode/AGENTS.md"));
    assert_eq!(
        navigation(&read("AGENTS.md")),
        standing,
        "AGENTS.md and opencode/AGENTS.md give the same rule"
    );
    let skill = read("skills/ast-explore/SKILL.md");
    let description = &frontmatter(&skill).unwrap()["description"];
    assert!(
        Regex::new("when ast-outline and ast-grep are on PATH.*otherwise use rg")
            .unwrap()
            .is_match(description)
    );
    let body = skill
        .splitn(3, "---\n")
        .nth(2)
        .unwrap()
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ");
    for phrase in [
        "When `ast-outline` and `ast-grep` are on PATH",
        "`just install-tools`",
        "Otherwise use `rg` and scoped reads",
        "do not retry or install the missing tools",
    ] {
        assert!(
            standing.contains(phrase),
            "opencode/AGENTS.md says {phrase}"
        );
        assert!(
            body.contains(phrase),
            "skills/ast-explore/SKILL.md says {phrase}"
        );
    }
}

