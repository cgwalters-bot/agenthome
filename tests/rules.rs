// The executor refuses a whole batch on one line it does not accept, losing
// the pass's `replace_state`, so the skill's examples must be agent-board's.
// The fixture is the `jsonl` example block of agent-board's
// docs/supervisor-requests.md at the commit the README pins; a sync changes
// commit, fixture and skill in one visible diff.
const AGENT_BOARD_COMMIT: &str = "9d36c74f5b8a71f94d9a95583f473591f37ec001";

/// The lines of the one `supervisor-actions` fenced block in `text`.
fn actions_block(text: &str) -> Result<&str> {
    let blocks: Vec<_> = Regex::new(r"(?ms)^```supervisor-actions\n(.*?)^```$")
        .unwrap()
        .captures_iter(text)
        .map(|c| c.get(1).unwrap().as_str())
        .collect();
    ensure!(blocks.len() == 1, "exactly one supervisor-actions block");
    Ok(blocks[0])
}

#[test]
fn the_supervisor_skill_sends_agent_boards_requests_at_the_pinned_commit() {
    let skill = read("skills/supervisor/SKILL.md");
    assert_eq!(
        actions_block(&skill).unwrap(),
        read("tests/fixtures/agent-board-supervisor-actions.jsonl")
    );
    assert!(
        read("README.md").contains(AGENT_BOARD_COMMIT),
        "README records the pinned commit"
    );
    // agent-board refuses the old close receipt and signs every write itself.
    assert!(!skill.contains("Triage found this issue done"));
    assert!(skill.contains("`schedule-triage`"));
    let profile = read(".github/agentic-job/profiles/supervisor.md");
    assert!(!profile.contains("Generated-by"));
    // Both state the capacity goal, so idle capacity is never reported on-track.
    for text in [&skill, &profile] {
        assert!(
            text.replace('\n', " ")
                .contains("under its pace with free slots is a finding")
        );
    }
    assert!(
        !skill
            .replace('\n', " ")
            .contains("Leave routine watching, pacing")
    );
    assert!(actions_block("No block.\n").is_err());
    assert_eq!(
        actions_block("```supervisor-actions\n{}\n```\n").unwrap(),
        "{}\n"
    );
}

#[test]
fn the_check_refuses_each_kind_of_bad_input() {
    let skill =
        |name: &str| format!("---\nname: {name}\ndescription: Load when testing.\n---\n\nBody.\n");
    let files = |entries: &[(&str, String)]| -> BTreeMap<String, String> {
        entries
            .iter()
            .map(|(path, text)| (path.to_string(), text.clone()))
            .collect()
    };
    let good = files(&[("demo/SKILL.md", skill("demo"))]);
    let agents = "Load the `demo` skill when testing.\n".to_owned();
    check_rules(&agents, &good).unwrap();
    check_rules(
        &format!("{agents}See https://github.com/cgwalters-forge/agenthome.\n"),
        &good,
    )
    .unwrap();
    let mut bads = vec![
        ("x\n".repeat(MAX_AGENTS_LINES + 1), good.clone()),
        (agents.clone(), files(&[("demo/SKILL.md", skill("other"))])),
        (
            agents.clone(),
            files(&[(
                "demo/SKILL.md",
                "---\nname: demo\ndescription:\n---\n".into(),
            )]),
        ),
        (
            agents.clone(),
            files(&[("demo/SKILL.md", "No frontmatter.\n".into())]),
        ),
        (
            format!("{agents}Load the `missing` skill too.\n"),
            good.clone(),
        ),
        (format!("{agents}`{NOTICE}` Ask cgwalters.\n"), good.clone()),
        (format!("{agents}`{FOOTER}` Ask cgwalters.\n"), good.clone()),
    ];
    for word in [
        "cgwalters",
        "CGWalters-bot",
        "cgwalters-bot",
        "bot-land",
        "bot-pr",
        "bot-operator",
        "bot-git",
        "bootstrap.md",
        "worker-preamble",
    ] {
        bads.push((format!("{agents}See {word} here.\n"), good.clone()));
        let mut files = good.clone();
        files.insert("demo/notes.md".into(), format!("Run {word}.\n"));
        bads.push((agents.clone(), files));
    }
    for (agents, files) in bads {
        assert!(
            check_rules(&agents, &files).is_err(),
            "{agents:?} {files:?}"
        );
    }
}
