//! Rules for the standing rules, skills and documents every run receives,
//! and for the repository itself.

use std::{
    collections::{BTreeMap, HashSet},
    fs,
    path::Path,
};

use anyhow::{Context, Result, ensure};
use regex::Regex;

fn root() -> &'static Path {
    Path::new(env!("CARGO_MANIFEST_DIR"))
}

fn read(path: &str) -> String {
    fs::read_to_string(root().join(path)).unwrap_or_else(|e| panic!("read {path}: {e}"))
}

const MAX_AGENTS_LINES: usize = 60;

// The standing rules reach every run, so they name no operator or bot login
// (a run must not act for whoever happens to be written here; how a run
// learns the logins is still undecided) and no frozen homegit tool a run
// cannot call. The commit trailer, the PR footer and the generated-document
// notice are the only places a login may appear: they name the operator as
// the author of the published LLM policy, not as an identity the agent assumes.
const ATTRIBUTION: &str = "Generated-by: https://github.com/cgwalters/#llms";

// The footer every bot-written pull request description, review and comment
// ends with (the operator's convention across the forge's bots); like the
// trailer it names the operator only as the policy's author.
const FOOTER: &str = "Generated-by: https://github.com/cgwalters/#llms";

// The generated-document notice (forge-infra docs/repository-checklist.md,
// "Generated documents"), pinned verbatim: like the trailer it names the
// operator only as the policy's author, never a model, provider or tool.
const NOTICE: &str = "> This text was generated by an LLM ([how cgwalters uses LLMs](https://github.com/cgwalters/cgwalters#llms)). cgwalters has not reviewed it yet.";

// Markdown that is input to an agent, not a document for people, carries no
// notice; everything else in this repository does. roles/ holds role prompts
// and the agents rendered from them.
const NOTICE_EXEMPT: &str = r"(^|/)(AGENTS|CLAUDE|SKILL)\.md$|^workflow/|^\.github/|^roles/";

// Login and homegit-tool patterns. A login followed by `-forge` is a link
// to the organization and allowed.
const FORBIDDEN: [&str; 7] = [
    r"(?i)\bcgwalters(-bot)?\b",
    r"(?i)bot-land",
    r"(?i)bot-pr",
    r"(?i)bot-operator",
    r"(?i)bot-git",
    r"(?i)bootstrap\.md",
    r"(?i)worker-preamble",
];

fn forbidden(text: &str) -> Option<String> {
    for pattern in FORBIDDEN {
        let regex = Regex::new(pattern).unwrap();
        let found = regex.find_iter(text).find(|found| {
            !text[found.end()..]
                .get(..6)
                .is_some_and(|next| next.eq_ignore_ascii_case("-forge"))
        });
        if let Some(found) = found {
            return Some(format!("{pattern} matches {:?}", found.as_str()));
        }
    }
    None
}

/// Only the `name: value` lines these files use, not general YAML.
fn frontmatter(text: &str) -> Result<BTreeMap<String, String>> {
    let meta = text
        .strip_prefix("---\n")
        .and_then(|rest| rest.split_once("\n---\n"))
        .context("starts with YAML frontmatter")?
        .0;
    Ok(meta
        .lines()
        .map(|line| {
            let (key, value) = line.split_once(':').unwrap_or((line, ""));
            (key.trim().to_owned(), value.trim().to_owned())
        })
        .collect())
}

/// `agents` is opencode/AGENTS.md; `files` maps each path under skills/ to
/// its text.
fn check_rules(agents: &str, files: &BTreeMap<String, String>) -> Result<()> {
    let lines = agents.lines().count();
    ensure!(
        lines <= MAX_AGENTS_LINES,
        "opencode/AGENTS.md has {lines} lines, at most {MAX_AGENTS_LINES}"
    );
    let mut skills = HashSet::new();
    for (path, text) in files {
        let Some((dir, "SKILL.md")) = path.split_once('/') else {
            continue;
        };
        let meta = frontmatter(text).with_context(|| path.clone())?;
        ensure!(
            meta.get("name").map(String::as_str) == Some(dir),
            "{path}: name matches its directory"
        );
        ensure!(
            meta.get("description").is_some_and(|d| !d.is_empty()),
            "{path}: description is non-empty"
        );
        skills.insert(dir);
    }
    for named in Regex::new(r"`([\w-]+)`\s+skill")
        .unwrap()
        .captures_iter(agents)
    {
        ensure!(
            skills.contains(&named[1]),
            "opencode/AGENTS.md names missing skill {}",
            &named[1]
        );
    }
    let checked = [("opencode/AGENTS.md".to_owned(), agents)]
        .into_iter()
        .chain(
            files
                .iter()
                .map(|(p, t)| (format!("skills/{p}"), t.as_str())),
        );
    for (path, text) in checked {
        let text = text
            .replace(ATTRIBUTION, "")
            .replace(FOOTER, "")
            .replace(NOTICE, "");
        if let Some(found) = forbidden(&text) {
            anyhow::bail!("{path} must not match: {found}");
        }
    }
    Ok(())
}

/// Files under `dir`, relative to it, skipping Git metadata and build output.
fn walk(dir: &Path) -> Vec<String> {
    fn visit(root: &Path, dir: &Path, out: &mut Vec<String>) {
        for entry in fs::read_dir(dir).unwrap() {
            let entry = entry.unwrap();
            let path = entry.path();
            let name = entry.file_name();
            if entry.file_type().unwrap().is_dir() {
                if name != ".git" && name != "node_modules" && path != root.join("target") {
                    visit(root, &path, out);
                }
            } else {
                let relative = path.strip_prefix(root).unwrap();
                out.push(relative.to_str().unwrap().to_owned());
            }
        }
    }
    let mut out = Vec::new();
    visit(dir, dir, &mut out);
    out.sort();
    out
}

fn read_skills() -> BTreeMap<String, String> {
    let dir = root().join("skills");
    walk(&dir)
        .into_iter()
        .map(|path| {
            let text = fs::read_to_string(dir.join(&path)).unwrap();
            (path, text)
        })
        .collect()
}

#[test]
fn standing_rules_and_skills_meet_the_repository_rules() {
    let files = read_skills();
    assert!(
        files.contains_key("ast-explore/SKILL.md"),
        "skills/ were read"
    );
    check_rules(&read("opencode/AGENTS.md"), &files).unwrap();
}

